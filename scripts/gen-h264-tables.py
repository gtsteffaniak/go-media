#!/usr/bin/env python3
"""Generate numeric constant tables for the clean-room H.264 decoder.

Input is plain text extracted from ITU-T Rec. H.264 (03/2010), for example:

    python3 -c "import pypdf; r=pypdf.PdfReader('h264.pdf'); \
        open('h264.txt','w').write('\n'.join(p.extract_text() or '' for p in r.pages))"

Usage: scripts/gen-h264-tables.py h264.txt internal/h264/cleanroom

Only the numeric tables printed in the specification are transcribed (CABAC
context initialisation for I slices, rangeTabLPS, state transitions, the 8x8
significance context map, default scaling lists, deblocking alpha/beta/tC0 and
zig-zag scans).  No third-party decoder source is read or copied.
"""
import re
import sys
from pathlib import Path


def load(path):
    return Path(path).read_text(encoding="utf-8").replace("\u2212", "-")


def ints(line):
    try:
        return [int(x) for x in line.split()]
    except ValueError:
        return None


def go_array(name, typ, rows, per_line=16, doc=None):
    out = []
    if doc:
        out.append("// " + doc)
    flat = isinstance(rows[0], int)
    if flat:
        out.append(f"var {name} = [{len(rows)}]{typ}{{")
        for i in range(0, len(rows), per_line):
            out.append("\t" + ", ".join(str(v) for v in rows[i : i + per_line]) + ",")
        out.append("}")
    else:
        out.append(f"var {name} = [{len(rows)}][{len(rows[0])}]{typ}{{")
        for r in rows:
            out.append("\t{" + ", ".join(str(v) for v in r) + "},")
        out.append("}")
    return "\n".join(out) + "\n"


def heading(lines, prefix):
    """Index of the table caption line (not a table-of-contents entry)."""
    for i, l in enumerate(lines):
        if l.startswith(prefix) and "\u2013" in l and "...." not in l:
            return i
    raise SystemExit("missing " + prefix)


def cabac_init_i(lines):
    mn = {}

    def find(prefix):
        return heading(lines, prefix)

    # Table 9-12: ctxIdx 0..10
    i = find("Table 9-12 ")
    for k in range(i, i + 12):
        if lines[k].startswith("m "):
            m = ints(lines[k][2:])
        if lines[k].startswith("n "):
            n = ints(lines[k][2:])
    assert len(m) == 11 and len(n) == 11
    for c in range(11):
        mn[c] = (m[c], n[c])

    # Table 9-16: I slices rows for ctxIdx 399..401
    i = find("Table 9-16 ")
    for k in range(i, i + 14):
        if lines[k].startswith("I slices m"):
            mm = ints(lines[k].replace("I slices m", "").replace("na", "").strip())
        if lines[k].startswith("n na"):
            nn = ints(lines[k].replace("n", "", 1).replace("na", "").strip())
    for c, a, b in zip((399, 400, 401), mm, nn):
        mn[c] = (a, b)

    # Table 9-17: ctxIdx 60..69 (all slice types)
    i = find("Table 9-17 ")
    for k in range(i, i + 10):
        if lines[k].startswith("m "):
            m = ints(lines[k][2:])
        if lines[k].startswith("n "):
            n = ints(lines[k][2:])
    for c in range(10):
        mn[60 + c] = (m[c], n[c])

    # Tables 9-18 .. 9-33: row layout "ctxIdx (m n)x4 [ctxIdx (m n)x4]"; first pair is I/SI.
    start = find("Table 9-18 ")
    end = find("Table 9-34 ")
    for l in lines[start:end]:
        v = ints(l)
        if v and len(v) in (9, 18):
            for k in range(0, len(v), 9):
                ctx = v[k]
                if ctx in mn and ctx >= 70:
                    # The specification text prints ctxIdx 541 as 641 in one row.
                    if ctx == 641 and 541 not in mn:
                        ctx = 541
                    else:
                        raise SystemExit(f"duplicate ctxIdx {ctx}")
                mn[ctx] = (v[k + 1], v[k + 2])
    return mn


def main():
    spec, outdir = sys.argv[1], Path(sys.argv[2])
    text = load(spec)
    lines = text.split("\n")
    hdr = "// Code generated by scripts/gen-h264-tables.py from ITU-T H.264 (03/2010); DO NOT EDIT.\n\n"

    # ---- CABAC package tables ----
    mn = cabac_init_i(lines)
    needed = [c for c in list(range(0, 11)) + list(range(60, 460)) + [399, 400, 401] if c != 276]
    for c in needed:
        assert c in mn, c
    m_arr = [mn.get(c, (0, 0))[0] for c in range(1024)]
    n_arr = [mn.get(c, (0, 0))[1] for c in range(1024)]

    # rangeTabLPS
    i = heading(lines, "Table 9-44 ")
    rng = {}
    for l in lines[i : i + 60]:
        v = ints(l)
        if v and len(v) in (5, 10):
            for k in range(0, len(v), 5):
                rng[v[k]] = v[k + 1 : k + 5]
    assert sorted(rng) == list(range(64)), sorted(rng)
    range_lps = [rng[s] for s in range(64)]

    i = heading(lines, "Table 9-45 ")
    lps, mps = [], []
    for l in lines[i : i + 14]:
        if l.startswith("transIdxLPS"):
            lps += ints(l[len("transIdxLPS") :])
        elif l.startswith("transIdxMPS"):
            mps += ints(l[len("transIdxMPS") :])
    assert len(lps) == 64 and len(mps) == 64

    # Table 9-43 (8x8 significance maps), levelListIdx 0..62
    sig, last = {}, {}
    i = heading(lines, "Table 9-43 ")
    for l in lines[i : i + 140]:
        v = ints(l)
        if v and len(v) in (4, 8):
            for k in range(0, len(v), 4):
                sig[v[k]] = v[k + 1]
                last[v[k]] = v[k + 3]
    sig_map = [sig[k] for k in range(63)]
    last_map = [last[k] for k in range(63)]

    body = hdr + "package cabac\n\n"
    body += go_array("initM", "int8", m_arr, doc="initM / initN are the m and n values of Tables 9-12 to 9-33 for I and SI slices, indexed by ctxIdx.")
    body += "\n" + go_array("initN", "int8", n_arr)
    body += "\n" + go_array("rangeTabLPS", "uint8", range_lps, doc="rangeTabLPS is Table 9-44, indexed [pStateIdx][qCodIRangeIdx].")
    body += "\n" + go_array("transIdxLPS", "uint8", lps, doc="transIdxLPS and transIdxMPS are Table 9-45.")
    body += "\n" + go_array("transIdxMPS", "uint8", mps)
    body += "\n" + go_array("Sig8x8Frame", "uint8", sig_map, doc="Sig8x8Frame is the ctxIdxInc of significant_coeff_flag for 8x8 blocks in frame macroblocks (Table 9-43).")
    body += "\n" + go_array("Last8x8", "uint8", last_map, doc="Last8x8 is the ctxIdxInc of last_significant_coeff_flag for 8x8 blocks (Table 9-43).")
    (outdir / "cabac" / "tables_gen.go").write_text(body)

    # ---- syntax package: default scaling lists ----
    def grab(prefix, count):
        vals = []
        for l in lines:
            if l.startswith(prefix):
                vals += ints(l[len(prefix) :])
        assert len(vals) == count, (prefix, len(vals))
        return vals

    def grab_pref(name, count):
        vals = []
        for l in lines:
            if l.startswith(name + "[ idx ]"):
                vals += ints(l[len(name + "[ idx ]") :])
        assert len(vals) == count, (name, len(vals))
        return vals

    body = hdr + "package syntax\n\n"
    body += go_array("Default4x4Intra", "uint8", grab_pref("Default_4x4_Intra", 16), doc="Default scaling lists in zig-zag order (Tables 7-3 and 7-4).")
    body += "\n" + go_array("Default4x4Inter", "uint8", grab_pref("Default_4x4_Inter", 16))
    body += "\n" + go_array("Default8x8Intra", "uint8", grab_pref("Default_8x8_Intra", 64))
    body += "\n" + go_array("Default8x8Inter", "uint8", grab_pref("Default_8x8_Inter", 64))

    # zig-zag scans
    def scan(label, count, which):
        vals = []
        i = heading(lines, label)
        for l in lines[i : i + 30]:
            if l.startswith(which + " c"):
                for a, b in re.findall(r"c\s*(\d)\s*(\d)", l):
                    vals.append((int(a), int(b)))
            if l.startswith("Table") and not l.startswith(label[:8]) and vals:
                break
        return vals

    z4 = [r * 4 + c for r, c in scan("Table 8-13 ", 16, "zig-zag")][:16]
    z8 = []
    i = heading(lines, "Table 8-14 ")
    for l in lines[i : i + 20]:
        if l.startswith("zig-zag c"):
            z8 += [int(a) * 8 + int(b) for a, b in re.findall(r"c\s*(\d)\s*(\d)", l)]
    assert len(z4) == 16 and len(z8) == 64
    body += "\n" + go_array("ZigZag4x4", "uint8", z4, doc="ZigZag4x4[idx] is the raster position row*4+col of coefficient idx in frame macroblocks (Table 8-13).")
    body += "\n" + go_array("ZigZag8x8", "uint8", z8, doc="ZigZag8x8[idx] is the raster position row*8+col (Table 8-14).")
    (outdir / "syntax" / "tables_gen.go").write_text(body)

    # ---- dsp package: deblocking tables ----
    def table_rows(label, row_prefixes, count):
        i = heading(lines, label)
        res = {p: [] for p in row_prefixes}
        for l in lines[i : i + 24]:
            for p in row_prefixes:
                if l.startswith(p):
                    res[p] += ints(l[len(p) :])
        return res

    alpha = []
    beta = []
    i = heading(lines, "Table 8-16 ")
    for l in lines[i : i + 14]:
        if l.startswith("\u03b1\u2032"):
            alpha += ints(l[2:])
        if l.startswith("\u03b2\u2032"):
            beta += ints(l[2:])
    assert len(alpha) == 52 and len(beta) == 52, (len(alpha), len(beta))
    i = heading(lines, "Table 8-17 ")
    tc0 = {1: [], 2: [], 3: []}
    for l in lines[i : i + 16]:
        m = re.match(r"bS = ([123])\s+(.*)", l)
        if m:
            tc0[int(m.group(1))] += ints(m.group(2))
    assert all(len(v) == 52 for v in tc0.values()), {k: len(v) for k, v in tc0.items()}

    body = hdr + "package dsp\n\n"
    body += go_array("alphaTab", "uint8", alpha, doc="alphaTab and betaTab are Table 8-16, indexed by indexA / indexB.")
    body += "\n" + go_array("betaTab", "uint8", beta)
    body += "\n" + go_array("tc0Tab", "uint8", [tc0[1], tc0[2], tc0[3]], doc="tc0Tab[bS-1][indexA] is Table 8-17.")
    (outdir / "dsp" / "tables_gen.go").write_text(body)


if __name__ == "__main__":
    main()
