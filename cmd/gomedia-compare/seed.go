func copyPinnedCompareAV1(id, dst string) error {
	var fileName, sha string
	switch id {
	case "mp4_av1":
		fileName, sha = compareMP4AV1File, compareMP4AV1SHA
	case "mkv_av1":
		fileName, sha = compareMKVAV1File, compareMKVAV1SHA
	case "webm_av1":
		fileName, sha = compareWebMAV1File, compareWebMAV1SHA
	case "avif_coded":
		fileName, sha = compareAVIFCodedFile, compareAVIFCodedSHA
	default:
		return fmt.Errorf("not a pinned AV1 fixture: %s", id)
	}
	src := filepath.Join(findRepoRoot("."), "test", "data", fileName)
	if ok, err := fileMatchesSHA256(src, sha); err != nil {
		return err
	} else if !ok {
		return fmt.Errorf("%s checksum mismatch (expected %s)", src, sha)
	}
	return copyFile(src, dst)
}

// ensurePinnedAssetsForSelectors installs checked-in test/data files into .assets when
// running a subset compare without regenerating the full ffmpeg matrix.
func ensurePinnedAssetsForSelectors(assetsDir, selectorsRaw string) error {
	tokens := parseAssetSelectors(selectorsRaw)
	if len(tokens) == 0 {
		return nil
	}
	imgDir := filepath.Join(assetsDir, "image")
	if err := os.MkdirAll(imgDir, 0o755); err != nil {
		return err
	}
	if assetMatchesAnySelector("jxl_unsplash", tokens) {
		dst := filepath.Join(imgDir, referenceJXLUnsplash)
		if _, err := os.Stat(dst); err != nil {
			if err := copyReferenceJXLUnsplash(dst); err != nil {
				return fmt.Errorf("jxl pinned fixture: %w", err)
			}
		}
		display := filepath.Join(imgDir, "jxl_unsplash_display.png")
		if _, err := os.Stat(display); err != nil {
			if err := copyReferenceJXLDisplayPNG(display); err != nil {
				return fmt.Errorf("jxl display sidecar: %w", err)
			}
		}
	}
	if assetMatchesAnySelector("heic_phone_primary", tokens) {
		heic := filepath.Join(imgDir, "heic_phone_primary.heic")
		if _, err := os.Stat(heic); err != nil {
			if err := copyReferenceSoundboardHEIC(heic); err != nil {
				return fmt.Errorf("heic phone pinned fixture: %w", err)
			}
		}
		display := filepath.Join(imgDir, "heic_phone_primary_display.png")
		if _, err := os.Stat(display); err != nil {
			if err := copyReferenceSoundboardDisplayPNG(display); err != nil {
				return fmt.Errorf("heic phone display sidecar: %w", err)
			}
		}
	}
	return nil
}

// ensureSeed copies the checked-in reference clip into destDir and verifies
// its checksum.
func ensureSeed(destDir string) (string, error) {
	if err := os.MkdirAll(destDir, 0o755); err != nil {
		return "", err
	}
	path := filepath.Join(destDir, seedFileName)
	if ok, err := fileMatchesSHA256(path, seedSHA256); err != nil {
		return "", err
	} else if ok {
		return path, nil
	}
	if err := copyFile(seedSourcePath(), path); err != nil {
		return "", fmt.Errorf("seed: %w", err)
	}
	if ok, err := fileMatchesSHA256(path, seedSHA256); err != nil {
		return "", err
	} else if !ok {
		return "", fmt.Errorf("seed checksum mismatch (expected %s)", seedSHA256)
	}
	return path, nil
}

// fileMatchesSHA256 reports whether path exists and matches wantHex.
func fileMatchesSHA256(path, wantHex string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		if os.IsNotExist(err) {
			return false, nil
		}
		return false, err
	}
	defer f.Close()
	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return false, err
	}
	return hex.EncodeToString(h.Sum(nil)) == wantHex, nil
}
