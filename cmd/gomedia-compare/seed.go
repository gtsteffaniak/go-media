// The seed is the single reference clip every comparison fixture is derived
// from. It is checked into the repo (test/data) and verified by SHA-256.
const (
	seedFileName = "reference_1080_10s.mp4"
	seedSHA256   = "406e43b9b133af8de0027427f922ed3c5bcd647d018f25ddb0b7e200c4dade02"

	// seedWMV3FileName is the reference clip encoded to WMV3 (Main) on Windows,
	// since ffmpeg cannot encode WMV3. See copyReferenceWMV3.
	seedWMV3FileName = "reference_1080_10s_wmv3.wmv"
	seedWMV3SHA256   = "3aac947c163d24b4aa136f15cd842a7f18f96ba2ec38969841dcf6c31c4e2684"

	// referenceSoundboardHEIC is a real iPhone-style HEVC-primary still (irot metadata).
	// Pinned because ffmpeg 9.0.2 has no HEIF muxer (same pattern as WMV3).
	referenceSoundboardHEIC    = "reference_soundboard.heic"
	referenceSoundboardHEICSHA = "eca52795e2acb6123f40ef47b59611f1c4d20762bfff443ac929a47800a11a49"

	// referenceSoundboardDisplayPNG is ffmpeg 9 decode of referenceSoundboardHEIC (display-oriented
	// raster). Used as the ffmpeg thumbnail input for heic_phone_primary; not generated by go-media.
	referenceSoundboardDisplayPNG    = "reference_soundboard_display.png"
	referenceSoundboardDisplayPNGSHA = "4947957b6fae7025ff259067171c7884187563895530e98aea13796ab8785f6a"
)

// seedID is the short identifier shown in the report footer.
var seedID = seedSHA256[:12]

// seedSourcePath is the checked-in reference clip.
func seedSourcePath() string {
	return filepath.Join(findRepoRoot("."), "test", "data", seedFileName)
}

func referenceSoundboardHEICPath() string {
	return filepath.Join(findRepoRoot("."), "test", "data", referenceSoundboardHEIC)
}

func referenceSoundboardDisplayPNGPath() string {
	return filepath.Join(findRepoRoot("."), "test", "data", referenceSoundboardDisplayPNG)
}

// copyReferenceSoundboardHEIC installs the checked-in phone HEIC still.
func copyReferenceSoundboardHEIC(dst string) error {
	src := referenceSoundboardHEICPath()
	if ok, err := fileMatchesSHA256(src, referenceSoundboardHEICSHA); err != nil {
		return err
	} else if !ok {
		return fmt.Errorf("%s checksum mismatch (expected %s)", src, referenceSoundboardHEICSHA)
	}
	return copyFile(src, dst)
}

// copyReferenceSoundboardDisplayPNG installs the ffmpeg-decoded display raster for phone HEIC.
func copyReferenceSoundboardDisplayPNG(dst string) error {
	src := referenceSoundboardDisplayPNGPath()
	if ok, err := fileMatchesSHA256(src, referenceSoundboardDisplayPNGSHA); err != nil {
		return err
	} else if !ok {
		return fmt.Errorf("%s checksum mismatch (expected %s)", src, referenceSoundboardDisplayPNGSHA)
	}
	return copyFile(src, dst)
}

// ensureSeed copies the checked-in reference clip into destDir and verifies
// its checksum.
func ensureSeed(destDir string) (string, error) {
	if err := os.MkdirAll(destDir, 0o755); err != nil {
		return "", err
	}
	path := filepath.Join(destDir, seedFileName)
	if ok, err := fileMatchesSHA256(path, seedSHA256); err != nil {
		return "", err
	} else if ok {
		return path, nil
	}
	if err := copyFile(seedSourcePath(), path); err != nil {
		return "", fmt.Errorf("seed: %w", err)
	}
	if ok, err := fileMatchesSHA256(path, seedSHA256); err != nil {
		return "", err
	} else if !ok {
		return "", fmt.Errorf("seed checksum mismatch (expected %s)", seedSHA256)
	}
	return path, nil
}

// fileMatchesSHA256 reports whether path exists and matches wantHex.
func fileMatchesSHA256(path, wantHex string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		if os.IsNotExist(err) {
			return false, nil
		}
		return false, err
	}
	defer f.Close()
	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return false, err
	}
	return hex.EncodeToString(h.Sum(nil)) == wantHex, nil
}
