#!/usr/bin/env python3
"""Emit internal/vc1/ac_escape_generated.go from /tmp/vc1acdata.h."""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = Path("/tmp/vc1acdata.h")
OUT = ROOT / "internal" / "vc1" / "ac_escape_generated.go"

PAD = {
    "acDeltaLevel": 31,
    "acLastDeltaLevel": 44,
    "acDeltaRun": 57,
    "acLastDeltaRun": 10,
}


def rows_u8(decl: str) -> list[list[int]]:
    text = SRC.read_text()
    idx = text.find(decl)
    if idx < 0:
        raise SystemExit("missing " + decl)
    sub = text[idx:]
    start = sub.find("{")
    body = sub[start + 1 :]
    rows: list[list[int]] = []
    depth = 1
    i = 0
    row_start = 0
    while i < len(body) and depth > 0:
        c = body[i]
        if c == "{":
            depth += 1
            if depth == 2:
                row_start = i + 1
        elif c == "}":
            depth -= 1
            if depth == 1:
                chunk = body[row_start:i]
                nums = [int(x) for x in re.findall(r"\d+", chunk)]
                rows.append(nums)
            if depth == 0:
                break
        i += 1
    return rows


def emit(name: str, rows: list[list[int]], pad: int) -> list[str]:
    lines = [f"var {name} = [8][{pad}]uint8{{"]
    for row in rows:
        if len(row) < pad:
            row = row + [0] * (pad - len(row))
        elif len(row) > pad:
            row = row[:pad]
        lines.append("\t{" + ", ".join(str(x) for x in row) + "},")
    lines.append("}")
    return lines


def main() -> None:
    delta_level = rows_u8("vc1_delta_level_table[AC_MODES][31]")
    last_delta_level = rows_u8("vc1_last_delta_level_table[AC_MODES][44]")
    delta_run = rows_u8("vc1_delta_run_table[AC_MODES][57]")
    last_delta_run = rows_u8("vc1_last_delta_run_table[AC_MODES][10]")
    lines = [
        "// Code generated by tools/gen_vc1/gen_ac_escape.py; DO NOT EDIT.",
        "",
        "package vc1",
        "",
    ]
    lines += emit("acDeltaLevel", delta_level, 31)
    lines.append("")
    lines += emit("acLastDeltaLevel", last_delta_level, 44)
    lines.append("")
    lines += emit("acDeltaRun", delta_run, 57)
    lines.append("")
    lines += emit("acLastDeltaRun", last_delta_run, 10)
    lines.append("")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
