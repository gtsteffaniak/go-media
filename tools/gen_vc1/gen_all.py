#!/usr/bin/env python3
"""Emit internal/vc1/generated_tables.go from ffmpeg n6.1 factual tables (SMPTE 421)."""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "internal" / "vc1" / "generated_tables.go"


def extract_pairs(src: str, decl: str) -> list[tuple[int, int]]:
    idx = src.find(decl)
    if idx < 0:
        raise SystemExit("missing " + decl)
    sub = src[idx:]
    start = sub.find("{")
    end = sub.find("};", start)
    if end < 0:
        raise SystemExit("missing end " + decl)
    chunk = sub[start : end + 1]
    pairs = []
    for a, b in re.findall(r"\{\s*(0x[0-9A-Fa-f]+|\d+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*\}", chunk):
        pairs.append((int(a, 0), int(b, 0)))
    if not pairs:
        raise SystemExit("no pairs " + decl)
    return pairs


def main() -> None:
    msm = Path("/tmp/msmpeg4_vc1_data.c").read_text()
    vc1data = Path("/tmp/vc1data.c").read_text()
    wmv2 = Path("/tmp/wmv2data.c").read_text()

    mb_i = extract_pairs(msm, "const uint16_t ff_msmp4_mb_i_table[64][2]")
    dc0l = extract_pairs(msm, "const uint32_t ff_table0_dc_lum[120][2]")
    dc1l = extract_pairs(msm, "const uint32_t ff_table1_dc_lum[120][2]")
    dc0c = extract_pairs(msm, "const uint32_t ff_table0_dc_chroma[120][2]")
    dc1c = extract_pairs(msm, "const uint32_t ff_table1_dc_chroma[120][2]")

    pquant_block = vc1data.split("ff_vc1_pquant_table[3][32]")[1]
    rows = []
    for line in pquant_block.split("};")[0].split("{"):
        nums = [int(x, 0) for x in re.findall(r"0x[0-9A-Fa-f]+|\d+", line)]
        if len(nums) == 32:
            rows.append(nums)
    if len(rows) != 3:
        raise SystemExit(f"pquant rows {len(rows)}")

    wmv3_dc = [int(x, 0) for x in re.findall(r"0x[0-9A-Fa-f]+|\d+", vc1data.split("ff_wmv3_dc_scale_table[32]")[1].split("};")[0])][:32]

    def arr_from_decl(src: str, decl: str) -> list[int]:
        idx = src.find(decl)
        if idx < 0:
            raise SystemExit("missing " + decl)
        sub = src[idx:]
        start = sub.find("{")
        end = sub.find("};", start)
        body = sub[start + 1 : end]
        return [int(x, 0) for x in re.findall(r"0x[0-9A-Fa-f]+|\d+", body)]

    zz4_vals = arr_from_decl(vc1data, "ff_vc1_simple_progressive_4x4_zz [16]")
    st_a_vals = arr_from_decl(wmv2, "ff_wmv2_scantableA[64]")
    st_b_vals = arr_from_decl(wmv2, "ff_wmv2_scantableB[64]")

    def arr_u8(name: str, vals: list[int]) -> str:
        lines = [f"var {name} = [...]uint8{{"]
        for i in range(0, len(vals), 16):
            lines.append("\t" + ", ".join(str(v) for v in vals[i : i + 16]) + ",")
        lines.append("}")
        return "\n".join(lines)

    zz4 = arr_u8("zzSimple4x4", zz4_vals)
    st_a = arr_u8("zzWMV2A", st_a_vals)
    st_b = arr_u8("zzWMV2B", st_b_vals)

    parts = [
        "// Code generated by tools/gen_vc1/gen_all.py; DO NOT EDIT.",
        "",
        "package vc1",
        "",
        "type dcEntry struct{ code uint32; bits uint8; val int16 }",
        "",
        "var mbIntraCBP = [...]struct{ code uint32; bits uint8; val uint8 }{",
    ]
    for i, (code, bits) in enumerate(mb_i):
        parts.append(f"\t{{code: {code}, bits: {bits}, val: {i}}},")
    parts.append("}")
    parts.append("")

    def emit_dc(name: str, rows_in: list[tuple[int, int]]) -> None:
        parts.append(f"var {name} = [...]dcEntry{{")
        for i, (code, bits) in enumerate(rows_in):
            parts.append(f"\t{{code: {code}, bits: {bits}, val: {i - 119 if i >= 119 else i}}},")
        parts.append("}")
        parts.append("")

    # DC VLC indices 0..118 map to differential magnitude; escape at 119+
    for nm, data in (
        ("dcLuma0", dc0l),
        ("dcLuma1", dc1l),
        ("dcChroma0", dc0c),
        ("dcChroma1", dc1c),
    ):
        parts.append(f"var {nm} = [...]dcEntry{{")
        for i, (code, bits) in enumerate(data):
            val = i
            if i == 119:
                val = 119  # ESC
            parts.append(f"\t{{code: {code}, bits: {bits}, val: {val}}},")
        parts.append("}")
        parts.append("")

    parts.append("var pquantTable = [3][32]uint8{")
    for r in rows:
        parts.append("\t{" + ", ".join(str(x) for x in r) + "},")
    parts.append("}")
    parts.append("")
    parts.append("var wmv3DCScale = [...]uint8{" + ", ".join(str(x) for x in wmv3_dc) + "}")
    parts.append("")
    parts.append(zz4)
    parts.append("")
    parts.append(st_a)
    parts.append("")
    parts.append(st_b)
    parts.append("")

    OUT.write_text("\n".join(parts) + "\n")
    print("wrote", OUT, "bytes", OUT.stat().st_size)


if __name__ == "__main__":
    main()
