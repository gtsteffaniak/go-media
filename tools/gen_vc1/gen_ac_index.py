#!/usr/bin/env python3
"""Emit internal/vc1/ac_index_generated.go from ffmpeg vc1acdata.h (factual SMPTE tables)."""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = Path("/tmp/vc1acdata.h")
OUT = ROOT / "internal" / "vc1" / "ac_index_generated.go"

SIZES = [186, 169, 133, 149, 103, 103, 163, 167]
LAST = [119, 99, 85, 81, 67, 58, 126, 109]


def main() -> None:
    text = SRC.read_text()
    chunk = text.split("vc1_index_decode_table[AC_MODES][185][2]")[1].split("};")[0]
    pairs = [(int(a), int(b)) for a, b in re.findall(r"\{\s*(\d+)\s*,\s*(\d+)\s*\}", chunk)]
    expected = sum(SIZES)
    if len(pairs) < expected:
        raise SystemExit(f"pairs {len(pairs)} want {expected}")
    lines = [
        "// Code generated by tools/gen_vc1/gen_ac_index.py; DO NOT EDIT.",
        "",
        "package vc1",
        "",
        "type acIndexEntry struct{ skip, level uint8 }",
        "",
        f"var acLastIndex = [...]int{{{', '.join(str(x) for x in LAST)}}}",
        "",
        "var acIndexDecode = [8][186]acIndexEntry{",
    ]
    off = 0
    for mi, n in enumerate(SIZES):
        lines.append("\t{")
        for i in range(n):
            skip, level = pairs[off + i]
            lines.append(f"\t\t{i}: {{skip: {skip}, level: {level}}},")
        off += n
        lines.append("\t},")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT, "pairs", off)


if __name__ == "__main__":
    main()
