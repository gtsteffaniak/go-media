#!/usr/bin/env python3
"""Emit internal/vc1/ac_index_generated.go from ffmpeg vc1acdata.h (factual SMPTE tables)."""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/tmp/vc1acdata.h")
OUT = ROOT / "internal" / "vc1" / "ac_index_generated.go"

AC_MODES = 8
LAST = [119, 99, 85, 81, 67, 58, 126, 109]


def main() -> None:
    text = SRC.read_text()
    chunk = text.split("vc1_index_decode_table[AC_MODES][185][2] = {")[1]
    # Split the initializer into its per-mode sub-arrays by brace depth; each
    # mode's rows are a prefix of the 185-entry slot (the rest is zero fill).
    modes, depth, start = [], 0, 0
    for i, ch in enumerate(chunk):
        if ch == "{":
            if depth == 0:
                start = i
            depth += 1
        elif ch == "}":
            if depth == 0:
                break
            depth -= 1
            if depth == 0:
                modes.append(chunk[start:i + 1])
    if len(modes) != AC_MODES:
        raise SystemExit(f"modes {len(modes)} want {AC_MODES}")
    per_mode = [
        [(int(a), int(b)) for a, b in re.findall(r"\{\s*(\d+)\s*,\s*(\d+)\s*\}", m)]
        for m in modes
    ]
    lines = [
        "// Code generated by tools/gen_vc1/gen_ac_index.py; DO NOT EDIT.",
        "",
        "package vc1",
        "",
        "type acIndexEntry struct{ skip, level uint8 }",
        "",
        f"var acLastIndex = [...]int{{{', '.join(str(x) for x in LAST)}}}",
        "",
        "var acIndexDecode = [8][186]acIndexEntry{",
    ]
    for rows in per_mode:
        lines.append("\t{")
        for i, (skip, level) in enumerate(rows):
            lines.append(f"\t\t{i}: {{skip: {skip}, level: {level}}},")
        lines.append("\t},")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
