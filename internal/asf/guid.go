func guidFromBytes(b ...byte) GUID {
	var g GUID
	copy(g[:], b)
	return g
}

func readGUID(b []byte) (GUID, bool) {
	if len(b) < 16 {
		return GUID{}, false
	}
	var g GUID
	copy(g[:], b[:16])
	return g, true
}

func guidEqual(a, b GUID) bool {
	return a == b
}
